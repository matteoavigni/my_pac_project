_CATALOG_BY_TICKER = {item['ticker'].upper(): item for item in ETF_CATALOG}


def get_catalog_entry(ticker: str):
    if not ticker:
        return None
    return _CATALOG_BY_TICKER.get(ticker.upper().strip())


def search_catalog(query: str, limit: int = 8):
    q = (query or '').strip().lower()
    if not q:
        return ETF_CATALOG[:limit]

    terms = [t for t in q.split() if t]
    scored = []
    for item in ETF_CATALOG:
        ticker_l = item['ticker'].lower()
        name_l = item['name'].lower()
        cat_l = item['category'].lower()
        isin_l = item['isin'].lower()
        haystack = f"{ticker_l} {name_l} {cat_l} {isin_l} {item['keywords']}"
        if all(term in haystack for term in terms):
            # Prioritize ticker prefix matches
            score = 0 if ticker_l.startswith(q) else (1 if q in ticker_l else 2)
            scored.append((score, item))

    scored.sort(key=lambda pair: (pair[0], pair[1]['ticker']))
    return [pair[1] for pair in scored[:limit]]


